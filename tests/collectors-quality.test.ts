import { afterAll, describe, expect, it } from "vitest";
import { c12FileSize } from "../src/collectors/c12-file-size.js";
import { p4Commits, p5CentralVersioning, p6Codeowners } from "../src/collectors/p-process.js";
import { cleanupFixtures, evidenceOf, makeRepo, run1, valueOf } from "./fixture-repo.js";

afterAll(cleanupFixtures);

const lines = (n: number) => Array.from({ length: n }, (_, i) => `// ${i}`).join("\n");

describe("C12 · arquivos acima do limite", () => {
  it("percentual de arquivos de código acima do limite; ignora gerados, testes e pastas de build", async () => {
    const r = makeRepo();
    r.write("src/Big.cs", lines(600));
    r.write("src/Small1.cs", lines(10));
    r.write("src/Small2.cs", lines(10));
    r.write("src/Gen.g.cs", lines(900));
    r.write("src/Header.cs", `// <auto-generated>\n${lines(900)}`);
    r.write("tests/BigTest.cs", lines(900));
    r.write("obj/Debug/x.cs", lines(900));
    r.write("docs/readme.md", lines(900));
    const res = await run1(c12FileSize, r.ctx());
    expect(valueOf(res)).toBeCloseTo(33.33, 1); // 1 de 3
    expect(evidenceOf(res)[0]).toMatchObject({ path: "src/Big.cs", line: 1, note: "600 linhas (limite 500)" });
  });

  it("respeita max_file_lines da política e mede 0 com evidência quando nenhum estoura", async () => {
    const r = makeRepo();
    r.write("a.go", lines(100));
    expect(valueOf(await run1(c12FileSize, r.ctx({ max_file_lines: 50 })))).toBe(100);
    const clean = await run1(c12FileSize, r.ctx());
    expect(valueOf(clean)).toBe(0);
    expect(evidenceOf(clean)[0]).toMatchObject({ kind: "job" });
  });

  it("sem código-fonte é N/A", async () => {
    const r = makeRepo();
    r.write("a.md", "x");
    expect((await run1(c12FileSize, r.ctx())).status).toBe("not_applicable");
  });
});

describe("P4 · commits convencionais", () => {
  it("mede o percentual de commits convencionais e lista os demais como evidência", async () => {
    const r = makeRepo();
    const subjects = ["feat: a", "fix(api): b", "chore!: c", "docs: d", "refactor(x): e", "ajustes", "wip", "Update README.md"];
    subjects.forEach((s, i) => {
      r.write(`f${i}.txt`, String(i));
      r.commit(s);
    });
    const res = await run1(p4Commits, r.ctx());
    expect(valueOf(res)).toBe(62.5);
    expect(evidenceOf(res).map((e) => (e.kind === "commit" ? e.note : ""))).toEqual(["Update README.md", "wip", "ajustes"]);
  });

  it("histórico curto não mede", async () => {
    const r = makeRepo();
    r.commit("feat: a");
    expect((await run1(p4Commits, r.ctx())).status).toBe("unmeasured");
  });
});

describe("P5 · versionamento central", () => {
  const csproj = (v: boolean) => `<Project><ItemGroup><PackageReference Include="X"${v ? ' Version="1.0.0"' : ""} /></ItemGroup></Project>`;

  it(".NET sem Directory.Packages.props é absent", async () => {
    const r = makeRepo();
    r.write("a/A.csproj", csproj(true));
    r.write("b/B.csproj", csproj(true));
    expect(valueOf(await run1(p5CentralVersioning, r.ctx()))).toBe("absent");
  });

  it(".NET centralizado sem Version nos csproj é present+no-divergence; com Version é present", async () => {
    const r = makeRepo();
    r.write("Directory.Packages.props", "<Project><PropertyGroup><ManagePackageVersionsCentrally>true</ManagePackageVersionsCentrally></PropertyGroup></Project>");
    r.write("a/A.csproj", csproj(false));
    r.write("b/B.csproj", csproj(false));
    expect(valueOf(await run1(p5CentralVersioning, r.ctx()))).toBe("present+no-divergence");
    r.write("b/B.csproj", csproj(true));
    const res = await run1(p5CentralVersioning, r.ctx());
    expect(valueOf(res)).toBe("present");
    expect(evidenceOf(res)[0]).toMatchObject({ path: "b/B.csproj", line: 1 });
  });

  it("npm workspaces com versões divergentes é present; um projeto só é N/A", async () => {
    const r = makeRepo();
    r.write("package.json", JSON.stringify({ workspaces: ["pkg/*"], dependencies: { zod: "^4.0.0" } }));
    r.write("pkg/a/package.json", JSON.stringify({ dependencies: { zod: "^3.0.0" } }));
    expect(valueOf(await run1(p5CentralVersioning, r.ctx()))).toBe("present");
    const single = makeRepo();
    single.write("package.json", "{}");
    expect((await run1(p5CentralVersioning, single.ctx())).status).toBe("not_applicable");
  });
});

