import path from "node:path";
import type { Evidence } from "../schema/evidence.js";
import { capEvidence, isTestPath, jobEvidence, measured, notApplicable, round, type Collector } from "./context.js";

const SOURCE_EXT = new Set([
  ".cs", ".fs", ".vb", ".go", ".kt", ".kts", ".java", ".scala", ".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs",
  ".py", ".rb", ".php", ".rs", ".swift", ".c", ".cc", ".cpp", ".h", ".hpp", ".sql",
]);

const GENERATED_DIR = /(^|\/)(bin|obj|dist|build|target|out|vendor|wwwroot\/lib|Migrations|\.next|coverage)(\/|$)/;
const GENERATED_FILE =
  /(\.g\.cs|\.g\.i\.cs|\.designer\.cs|\.generated\.[a-z]+|\.pb\.go|_pb2\.py|\.pb\.cc|\.min\.js|\.bundle\.js|\.d\.ts|_gen\.go|\.xaml\.cs)$/i;

export function isSourceFile(rel: string): boolean {
  if (!SOURCE_EXT.has(path.posix.extname(rel).toLowerCase())) return false;
  return !GENERATED_DIR.test(rel) && !GENERATED_FILE.test(rel);
}

function looksGenerated(text: string): boolean {
  return /<auto-generated|@generated|DO NOT EDIT|Code generated .* DO NOT EDIT/i.test(text.split(/\r?\n/, 8).join("\n"));
}

export const c12FileSize: Collector = {
  ids: ["C12"],
  async run(ctx) {
    const limit = ctx.policy.max_file_lines;
    const sources = ctx.files.filter((f) => isSourceFile(f) && !isTestPath(f));
    const offenders: { rel: string; lines: number }[] = [];
    let analyzed = 0;
    for (const rel of sources) {
      const text = ctx.readText(rel);
      if (text === null || looksGenerated(text)) continue;
      analyzed += 1;
      const lines = text.split(/\r?\n/).length;
      if (lines > limit) offenders.push({ rel, lines });
    }
    if (analyzed === 0) return [notApplicable("C12", "nenhum arquivo de código-fonte encontrado")];

    offenders.sort((a, b) => b.lines - a.lines);
    const pct = round((offenders.length / analyzed) * 100, 2);
    const evidence: Evidence[] =
      offenders.length > 0
        ? capEvidence(
            offenders.map((o) => ({
              kind: "file" as const,
              path: o.rel,
              line: 1,
              note: `${o.lines} linhas (limite ${limit})`,
            })),
          )
        : [jobEvidence("c12-file-size", `${analyzed} arquivos de código analisados, nenhum acima de ${limit} linhas`)];
    return [measured("C12", pct, evidence)];
  },
};
