import path from "node:path";
import { isTestPath } from "../../../collectors/context.js";

/**
 * Definição ÚNICA de "arquivo de regra de negócio", usada pela descoberta (o que vira spec) e pelo D7 (o que conta
 * como lacuna). Se as duas divergissem, o plano projetaria uma nota que a medição não confirma.
 */
export const CODE_EXT = /\.(cs|fs|vb|go|kt|kts|java|scala|ts|tsx|js|jsx|mjs|py|rb|php|rs|swift|c|cc|cpp|h|hpp|sql)$/i;

/** Pastas só de dados/contratos/mensagens e interfaces: não carregam regra. */
const DATA_DIR = /(^|\/)(Dtos?|Models?|Entities|Commands|Migrations|RepositoryInterfaces|Interfaces|Properties)(\/|$)/i;
const INTERFACE_FILE = /^I[A-Z][A-Za-z0-9]*\.[a-z]+$/;

/** Infraestrutura: ponto de entrada, DI, configuração, mensagens, contexto de ORM, observabilidade. */
const PLUMBING_FILE = /(^|\/)(Program|Startup|Worker|MessageReceiver)\.[a-z]+$|(Extensions|Module|Configuration|Settings|Options|Context|Messages?|Dto|Request|Response|Command|Builder|Mapper|Profile|Window|View|ViewModel|Page|Control)\.[a-z]+$/;
const PLUMBING_DIR = /(^|\/)(Messages|Setup|Telemetry|Infrastructure|Mappings?|Acl|Avro|Views?|ViewModels?|Controls)(\/|$)/i;
/** Enums e constantes vão para o glossário (spec 01), não para specs de regra. */
const GLOSSARY_DIR = /(^|\/)(Enums?|Constants?)(\/|$)/i;

/** Projetos de teste que o `isTestPath` não reconhece (ex.: `*.IntegrationTest/`). */
const TEST_DIR = /(^|\/)[^/]*(IntegrationTests?|UnitTests?|LoadTests?|E2E|Tests?)(\/|$)/;

export const isTestLike = (rel: string) => isTestPath(rel) || TEST_DIR.test(rel);

/** Código gerado (Avro, protobuf, etc.): reconhecido pelo cabeçalho. */
export const isGeneratedText = (text: string) => /<auto-generated|@generated|DO NOT EDIT|ISpecificRecord|Avro\.Specific|\[GeneratedCode\(/.test(text.slice(0, 1500));

/** Filtro só por caminho: usado em citações de specs (permissivo com infraestrutura que a spec decidiu citar). */
export function isRuleCandidate(rel: string): boolean {
  return CODE_EXT.test(rel) && !isTestLike(rel) && !DATA_DIR.test(rel) && !INTERFACE_FILE.test(path.posix.basename(rel));
}

export interface RuleFile {
  path: string;
  /** Linhas não vazias. */
  lines: number;
  /** Densidade de decisão: desvios, números, SQL. */
  density: number;
  role: "regra" | "handler" | "serviço" | "consulta" | "outro";
  methods: string[];
  chars: number;
}

const BRANCH = /\b(if|else|switch|case|while|foreach|when)\b|&&|\|\||\?\s*[^:\n]{1,40}:/g;
const NUMBER = /\b\d+(?:\.\d+)?m?\b/g;
const SQL = /\b(CASE|WHEN|SUM|AVG|POWER|DATEDIFF|COALESCE|ISNULL|GROUP BY|HAVING|JOIN)\b/gi;
const METHOD = /^\s*(?:(?:public|private|protected|internal|static|async|override|virtual|sealed)\s+)+[\w<>\[\],?.() ]+?\s+(\w+)\s*\(/gm;

function roleOf(rel: string): RuleFile["role"] {
  const b = path.posix.basename(rel);
  if (/Rule|Validator|Policy|Strategy|Calculator/.test(b)) return "regra";
  if (/Handler|Processor/.test(b)) return "handler";
  if (/Quer(y|ies)|Sql/.test(b)) return "consulta";
  if (/Service/.test(b)) return "serviço";
  return "outro";
}

export function methodsOf(text: string): string[] {
  const out = new Set<string>();
  for (const m of text.matchAll(METHOD)) {
    const n = m[1]!;
    if (!["if", "for", "while", "switch", "catch", "using", "lock", "foreach", "return", "new"].includes(n) && !/^(get|set)$/i.test(n)) out.add(n);
  }
  return [...out];
}

export function measureFile(rel: string, text: string): RuleFile {
  const lines = text.split(/\r?\n/).filter((l) => l.trim() !== "").length;
  const numbers = (text.match(NUMBER) ?? []).filter((n) => !["0", "1", "2"].includes(n)).length;
  const density = (text.match(BRANCH)?.length ?? 0) + numbers * 0.5 + (text.match(SQL)?.length ?? 0);
  return { path: rel, lines, density: Math.round(density), role: roleOf(rel), methods: methodsOf(text), chars: text.length };
}

export const MIN_RULE_LINES = 25;
export const MIN_RULE_DENSITY = 8;

export type RuleVerdict = { rule: true; file: RuleFile } | { rule: false; why: "caminho" | "infraestrutura" | "gerado" | "glossario" | "baixa-densidade" };

/** Este arquivo é regra de negócio? Mesma resposta para a descoberta e para o D7. */
export function classifyRuleFile(rel: string, text: string): RuleVerdict {
  if (!isRuleCandidate(rel)) return { rule: false, why: "caminho" };
  if (PLUMBING_FILE.test(rel) || PLUMBING_DIR.test(rel)) return { rule: false, why: "infraestrutura" };
  if (GLOSSARY_DIR.test(rel)) return { rule: false, why: "glossario" };
  if (isGeneratedText(text)) return { rule: false, why: "gerado" };
  const file = measureFile(rel, text);
  if (file.lines < MIN_RULE_LINES || file.density < MIN_RULE_DENSITY) return { rule: false, why: "baixa-densidade" };
  return { rule: true, file };
}
