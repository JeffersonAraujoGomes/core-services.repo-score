// Empacota o CLI em um único arquivo ESM, sem dependências em runtime (só Node >= 20).
// Restrições para permitir binário único depois: sem addons nativos e sem require dinâmico.
import { build } from "esbuild";
import { readFileSync, statSync } from "node:fs";

const outfile = "skill/scripts/repo-score.mjs";

await build({
  entryPoints: ["src/cli/main.ts"],
  outfile,
  bundle: true,
  platform: "node",
  target: "node20",
  format: "esm",
  sourcemap: false,
  legalComments: "none",
  loader: { ".html": "text", ".sh": "text", ".md": "text" },
  banner: { js: "// @generated by esbuild from src/ (core-services-repo-score). DO NOT EDIT: run `npm run build`." },
  logLevel: "info",
});

const code = readFileSync(outfile, "utf8");
const bad = [/require\(\s*[^"'\s)]/, /\.node["']/, /createRequire/].filter((re) => re.test(code));
if (bad.length) {
  console.error("bundle viola as restrições de empacotamento:", bad.map(String).join(", "));
  process.exit(1);
}
console.log(`ok: ${outfile} (${(statSync(outfile).size / 1024).toFixed(0)} KB)`);
