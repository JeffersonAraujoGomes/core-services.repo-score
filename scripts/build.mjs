// Empacota o CLI em um único arquivo ESM, sem dependências em runtime (só Node >= 20).
// Restrições para permitir binário único depois: sem addons nativos e sem require dinâmico.
//
// O bundle é gerado e NÃO deve ser editado. Para quem revisa ou audita:
//  - skill/references/provenance.json registra o commit de origem, as versões das ferramentas e o SHA-256 do bundle;
//  - o bundle é determinístico: o teste tests/bundle.test.ts o reconstrói a partir do src/ e compara o hash;
//  - a skill publicada não tem código que commite, mescle ou reverta: src/remediation/commit-paths.ts é trocado pelo
//    stub que só recusa (o teste confere a ausência de `git commit`, `--no-verify`, `merge` e `revert` no bundle).
import { build } from "esbuild";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outfile = path.join(root, "skill/scripts/repo-score.mjs");
const provenanceFile = path.join(root, "skill/references/provenance.json");
const skillMd = path.join(root, "skill/SKILL.md");
const BLOCK_START = "<!-- provenance:start (gerado por npm run build; não edite) -->";
const BLOCK_END = "<!-- provenance:end -->";

const sha256 = (buf) => createHash("sha256").update(buf).digest("hex");
const git = (...args) => {
  try {
    return execFileSync("git", args, { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch {
    return "";
  }
};

/** Opções do bundle publicado (usadas também pelo teste, que reconstrói em memória). */
export function bundleOptions(extra = {}) {
  return {
    absWorkingDir: root,
    entryPoints: ["src/cli/main.ts"],
    bundle: true,
    platform: "node",
    target: "node20",
    format: "esm",
    sourcemap: false,
    legalComments: "none",
    charset: "utf8", // acentos legíveis no bundle (facilita a revisão)
    loader: { ".html": "text", ".sh": "text", ".md": "text" },
    banner: { js: "// @generated by esbuild from src/ (core-services.repo-score). DO NOT EDIT: run `npm run build`. Origem, commit e SHA-256: skill/references/provenance.json." },
    plugins: [
      {
        name: "sem-caminho-de-commit",
        setup(b) {
          b.onResolve({ filter: /(^|\/)commit-paths\.js$/ }, () => ({ path: path.join(root, "src/remediation/commit-paths.stub.ts") }));
        },
      },
    ],
    logLevel: "silent",
    ...extra,
  };
}

export function renderProvenanceBlock(p) {
  const L = [
    BLOCK_START,
    "## Origem e integridade do bundle",
    "",
    "`scripts/repo-score.mjs` é **gerado** (esbuild) a partir do `src/` do projeto de origem e não deve ser editado à mão.",
    "",
    `- Projeto de origem: \`${p.project}\` v${p.version}${p.repository ? ` — ${p.repository}` : " (defina `repository` no package.json do projeto para registrar a URL aqui)"}`,
    `- Commit da fonte: \`${p.commit || "desconhecido"}\`${p.dirty ? " **(construído de uma árvore com alterações não commitadas: não reproduzível a partir do commit)**" : ""}`,
    `- SHA-256 do bundle: \`${p.bundle_sha256}\``,
    `- Ferramentas: Node ${p.node}, esbuild ${p.esbuild}, TypeScript ${p.typescript}`,
    "- A skill publicada **não tem código que commite, mescle ou reverta**: esse módulo é trocado por um stub que só recusa.",
    "",
    "Verificar: `node scripts/repo-score.mjs integrity` (compara o arquivo em execução com `references/provenance.json`) ou `shasum -a 256 scripts/repo-score.mjs`. Reproduzir: no commit acima, `npm ci && npm run build` e comparar o SHA-256.",
    BLOCK_END,
  ];
  return L.join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await build(bundleOptions({ outfile, logLevel: "info" }));

  const code = readFileSync(outfile, "utf8");
  const bad = [/require\(\s*[^"'\s)]/, /\.node["']/, /createRequire/].filter((re) => re.test(code));
  if (bad.length) {
    console.error("bundle viola as restrições de empacotamento:", bad.map(String).join(", "));
    process.exit(1);
  }
  const pkg = JSON.parse(readFileSync(path.join(root, "package.json"), "utf8"));
  const lock = (name) => {
    try {
      return JSON.parse(readFileSync(path.join(root, "node_modules", name, "package.json"), "utf8")).version;
    } catch {
      return "desconhecida";
    }
  };
  const provenance = {
    project: pkg.name,
    version: pkg.version,
    repository: (typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url) || git("remote", "get-url", "origin") || null,
    commit: git("rev-parse", "HEAD"),
    dirty: git("status", "--porcelain", "--", "src", "scripts", "ui", "package.json", "package-lock.json", "tsconfig.json") !== "",
    bundle_sha256: sha256(readFileSync(outfile)),
    bundle_bytes: statSync(outfile).size,
    node: process.versions.node,
    esbuild: lock("esbuild"),
    typescript: lock("typescript"),
  };
  writeFileSync(provenanceFile, JSON.stringify(provenance, null, 2) + "\n");

  // bloco gerado no SKILL.md (entre marcadores)
  const md = readFileSync(skillMd, "utf8");
  const block = renderProvenanceBlock(provenance);
  const re = new RegExp(`${BLOCK_START.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${BLOCK_END}`);
  const next = re.test(md) ? md.replace(re, () => block) : `${md.trimEnd()}\n\n${block}\n`;
  if (next !== md) writeFileSync(skillMd, next);
  console.log(`ok: ${path.relative(root, outfile)} (${(provenance.bundle_bytes / 1024).toFixed(0)} KB) sha256 ${provenance.bundle_sha256.slice(0, 12)}…${provenance.dirty ? " [árvore suja]" : ""}`);
}
